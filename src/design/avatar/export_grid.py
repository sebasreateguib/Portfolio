"""Writes src/data/avatar-grid.ts for the hero's pixel avatar (thermal-avatar.ts).

Reads the 96x96 art in avatar.png (each pixel a flat block of one of six greys),
applies the gaze retouch, and writes it as one string per row: '0'-'5' are the
six tones darkest first, '.' is the background (black connected to the border).
Also writes the closed-lid pixels for the blink, the glitch slices and the row
the breath lifts.

Re-run after changing avatar.png:  python3 src/design/avatar/export_grid.py
"""
import json
from collections import deque
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
SRC = HERE / "avatar.png"
OUT = HERE.parents[2] / "src" / "data" / "avatar-grid.ts"

N = 96            # logical grid size
BREATH_ROW = 84   # rows above this rise 1px on the inhale
BLACK = 0
PALETTE = [0, 42, 85, 138, 200, 242]  # the art's six greys, darkest first

EYE_BOX_L = (35, 33, 40, 35)   # x0, y0, x1, y1 inclusive
EYE_BOX_R = (53, 33, 59, 34)
# Gaze retouch, applied to the grid as it is read: in the source the right
# glint sits against the outer corner and the left one leans the other way,
# so the eyes diverge. Both glints are moved to the middle of their opening.
EYE_RETOUCH = {(37, 35): 42, (38, 35): 242, (56, 34): 242, (57, 34): BLACK}
PUPIL_L = {(37, 35): 42, (38, 35): 242}   # iris glint, left eye (retouched)
PUPIL_R = {(56, 34): 242}                 # iris glint, right eye (retouched)

# Glitch slices: [firstRow, lastRow, dx].
SLICES = [[21, 25, 5], [28, 31, -3], [49, 52, 4], [32, 36, 3], [58, 60, -3]]


def load_grid() -> list[list[int]]:
    im = Image.open(SRC).convert("L")
    w, h = im.size
    scale = w // N
    assert w == h == N * scale, f"expected a {N}x{N} grid, got {w}x{h}"
    px = im.load()
    grid = [[px[x * scale, y * scale] for x in range(N)] for y in range(N)]
    # every block must be a single flat colour
    for y in range(N):
        for x in range(N):
            c = grid[y][x]
            for dy in range(scale):
                for dx in range(scale):
                    assert px[x * scale + dx, y * scale + dy] == c, (x, y)
    for (x, y), c in EYE_RETOUCH.items():
        grid[y][x] = c
    return grid


def background(grid) -> set:
    """Black pixels 4-connected to the border: left empty."""
    seen = set()
    q = deque()
    for i in range(N):
        for p in ((i, 0), (i, N - 1), (0, i), (N - 1, i)):
            if grid[p[1]][p[0]] == BLACK and p not in seen:
                seen.add(p)
                q.append(p)
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (x + dx, y + dy)
            if 0 <= n[0] < N and 0 <= n[1] < N and n not in seen and grid[n[1]][n[0]] == BLACK:
                seen.add(n)
                q.append(n)
    return seen


def in_box(p, box):
    x0, y0, x1, y1 = box
    return x0 <= p[0] <= x1 and y0 <= p[1] <= y1


grid = load_grid()
bg = background(grid)
tone = {c: i for i, c in enumerate(PALETTE)}
rows = ["".join("." if (x, y) in bg else str(tone[grid[y][x]]) for x in range(N)) for y in range(N)]

# Closed lids: the eye openings and glints painted over in shadow greys.
pupils = {**PUPIL_L, **PUPIL_R}
MID, INK = 138, 42
lids = []
for y in range(N):
    for x in range(N):
        p = (x, y)
        in_eye = in_box(p, EYE_BOX_L) or in_box(p, EYE_BOX_R)
        if not in_eye or not ((grid[y][x] == BLACK and p not in bg) or p in pupils):
            continue
        if in_box(p, EYE_BOX_L):
            c = MID if y in (33, 34) else INK
        else:
            c = MID if y == 33 else INK
        lids.append([x, y, tone[c]])

OUT.write_text(
    "// Generated by src/design/avatar/export_grid.py from src/design/avatar/avatar.png.\n"
    "// Edit the generator, not this file.\n\n"
    "/** 96 rows of 96 cells: '0'-'5' tones (darkest first), '.' background. */\n"
    f"export const AVATAR_ROWS: readonly string[] = {json.dumps(rows, indent=2)}\n\n"
    "/** Closed eyelids for the blink: [x, y, tone]. */\n"
    f"export const AVATAR_LIDS: readonly (readonly [number, number, number])[] = {json.dumps(lids)}\n\n"
    "/** Glitch slices: [firstRow, lastRow, dx]. */\n"
    f"export const AVATAR_SLICES: readonly (readonly [number, number, number])[] = {json.dumps(SLICES)}\n\n"
    f"/** Rows above this rise one pixel on the inhale. */\nexport const AVATAR_BREATH_ROW = {BREATH_ROW}\n"
)
print(f"wrote {OUT} ({len(lids)} lid pixels)")
