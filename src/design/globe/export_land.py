"""Writes src/data/globe-land.ts for the hero's ASCII globe (ascii-globe.tsx).

Rasterises Natural Earth's 1:110m land polygons (public domain,
https://www.naturalearthdata.com, file ne_110m_land.geojson next to this script)
onto an equirectangular grid of W x H cells (0.5 degree each) and stores it as a
base64 bitmask, one bit per cell, row-major from 90N/180W, most significant bit
first.

Re-run after changing the source or the resolution:  python3 src/design/globe/export_land.py
"""
import base64
import json
from pathlib import Path

from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
SRC = HERE / "ne_110m_land.geojson"
OUT = HERE.parents[2] / "src" / "data" / "globe-land.ts"

W, H = 720, 360
SS = 4  # supersample, then a cell is land when at least half of it is

img = Image.new("L", (W * SS, H * SS), 0)
draw = ImageDraw.Draw(img)
for feature in json.loads(SRC.read_text())["features"]:
    geom = feature["geometry"]
    polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
    for poly in polys:
        for i, ring in enumerate(poly):
            pts = [((lon + 180) / 360 * W * SS, (90 - lat) / 180 * H * SS) for lon, lat in ring]
            draw.polygon(pts, fill=0 if i else 255)  # inner rings are lakes/holes

small = img.resize((W, H), Image.BOX)
px = small.load()
bits = bytearray(W * H // 8)
land = 0
for y in range(H):
    for x in range(W):
        if px[x, y] >= 128:
            i = y * W + x
            bits[i >> 3] |= 0x80 >> (i & 7)
            land += 1

b64 = base64.b64encode(bytes(bits)).decode()
OUT.write_text(
    "// Generated by src/design/globe/export_land.py from Natural Earth 1:110m land.\n"
    "// Edit the generator, not this file.\n\n"
    f"export const LAND_W = {W};\n"
    f"export const LAND_H = {H};\n"
    "/** Base64 bitmask, row-major from 90N/180W, MSB first: 1 = land. */\n"
    f'export const LAND_BITS = "{b64}";\n'
)
print(f"wrote {OUT} ({land / (W * H):.1%} land, {len(b64)} chars)")
